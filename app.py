"""Multibagger Scout AI - custom UI build. The full archive backend runs underneath; the UI is a custom component."""
import base64
import hmac
import os
import secrets
import sys

import streamlit as st

st.set_page_config(page_title="Multibagger Scout AI", layout="wide", initial_sidebar_state="collapsed")

for _k in ("DATABASE_URL", "APP_PASSWORD", "NSE_EQUITY_LIST_URL", "EXPORT_DIR", "NTFY_TOPIC", "NTFY_SERVER", "TELEGRAM_BOT_TOKEN", "TELEGRAM_CHAT_ID",
           "SMTP_HOST", "SMTP_PORT", "SMTP_USER", "SMTP_PASSWORD", "SMTP_FROM", "SMTP_TO", "WEBHOOK_URL"):
    if _k not in os.environ:
        try:
            if _k in st.secrets:
                os.environ[_k] = str(st.secrets[_k])
        except Exception:
            pass

_HERE = os.path.dirname(os.path.abspath(__file__))
_ARCHIVE = os.environ.get("SCOUT_ARCHIVE") or os.path.join(_HERE, "multibagger_scout_ai")  # bundled archive next to app.py on the host
for _p in (_HERE, _ARCHIVE, os.path.join(_ARCHIVE, "tests")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

_pw = os.environ.get("APP_PASSWORD", "")
if _pw and not st.session_state.get("auth_ok"):  # optional access gate, same mechanism as the archive app
    st.title("Multibagger Scout AI")
    _entered = st.text_input("Access password", type="password", key="pw")
    if _entered:
        if hmac.compare_digest(_entered.encode(), _pw.encode()):
            st.session_state["auth_ok"] = True
            st.rerun()
        else:
            st.error("Wrong password.")
    st.stop()

import handler  # noqa: E402
import streamlit.components.v1 as components  # noqa: E402

handler.scheduler()  # starts the in-process scheduler when enabled in settings

comp = components.declare_component("scout", path=os.path.join(_HERE, "component"))

st.session_state.setdefault("rpc", None)
st.session_state.setdefault("seen", None)
st.session_state.setdefault("visitor_id", secrets.token_hex(8))  # per browser session; isolates this visitor's workspace

event = comp(boot={"floors": handler.FLOOR_NAMES, "synthetic": handler.SYNTHETIC, "isolation": handler.ISOLATION,
                   "vid": st.session_state.visitor_id}, result=st.session_state.rpc, default=None, key="scout")
if event and event.get("nonce") != st.session_state.seen:
    st.session_state.seen = event.get("nonce")
    try:
        data = handler.dispatch(event, st.session_state)
    except Exception as exc:
        data = {"error": f"{type(exc).__name__}: {exc}"}
    st.session_state.rpc = {"nonce": event.get("nonce"), "action": event.get("action"), "data": handler.to_jsonable(data)}
    st.rerun()

_dls = st.session_state.get("downloads") or []
if _dls:  # real file downloads (component iframes cannot save files); generated by the app's own report generator
    st.caption("Generated report files:")
    _cols = st.columns(len(_dls))
    for _col, _d in zip(_cols, _dls):
        _payload = base64.b64decode(_d["data"]) if _d.get("b64") else _d["data"]
        _col.download_button(_d["label"], _payload, file_name=_d["name"], mime=_d["mime"], key="dl_" + _d["name"])
